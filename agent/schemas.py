"""
Pydantic Data Models for Autonomous AI Google Maps Lead Generation Agent.
"""

from typing import List, Optional, Literal
from pydantic import BaseModel, Field


class SubLocation(BaseModel):
    """Represents a micro-zone within a target city or region."""
    area_name: str = Field(description="Name of the neighborhood or micro-zone (e.g. 'Dhanmondi, Dhaka')")
    lat: float = Field(description="Center Latitude coordinate of this micro-zone")
    lon: float = Field(description="Center Longitude coordinate of this micro-zone")
    radius: float = Field(default=3500.0, description="Search radius in meters (typically 2500 - 4000)")


class FilterConfig(BaseModel):
    """Filtering criteria applied to scraped leads."""
    website_requirement: Literal["no_website", "has_real_website", "any"] = Field(
        default="any",
        description="'no_website' (includes Social Link Only), 'has_real_website', or 'any'"
    )
    must_have_phone: bool = Field(default=False, description="Require a phone number")
    must_have_email: bool = Field(default=False, description="Require at least one verified email when website enrichment is enabled")
    min_rating: float = Field(default=0.0, description="Minimum Google Maps rating (0.0 to 5.0)")
    min_reviews: int = Field(default=0, description="Minimum number of user reviews")
    max_pages_per_search: int = Field(
        default=3,
        description="Number of pages (offset 0, 20, 40...) to fetch per sub-location (1 to 6)"
    )


class EnrichmentConfig(BaseModel):
    """Website deep scraping and enrichment options."""
    enabled: bool = Field(default=False, description="Enable deep website scraping for emails/socials")
    extract_emails: bool = Field(default=False, description="Scrape emails from business website")
    extract_socials: bool = Field(default=False, description="Scrape Facebook, Instagram, LinkedIn, WhatsApp links")
    detect_cms: bool = Field(default=False, description="Detect CMS platform (WordPress, Shopify, Wix)")


class ActionPlan(BaseModel):
    """Strict execution plan generated by the AI Planner."""
    user_prompt: str = Field(description="Original user request in natural language")
    keywords: List[str] = Field(description="2 to 4 Google Maps business category keywords")
    country_code: str = Field(default="bd", description="Country code (e.g. 'bd', 'us', 'uk')")
    language: str = Field(default="en", description="Google search interface language (e.g. 'en')")
    sub_locations: List[SubLocation] = Field(
        description="List of geo-split micro-zones covering the target location"
    )
    target_leads: Optional[int] = Field(
        default=None,
        description="Exact number of leads requested by the user (e.g. 50, 100). None if unlimited/unspecified."
    )
    filters: FilterConfig = Field(default_factory=FilterConfig)
    enrichment: EnrichmentConfig = Field(default_factory=EnrichmentConfig)


class SocialLinks(BaseModel):
    """Extracted social media links."""
    facebook: Optional[str] = None
    instagram: Optional[str] = None
    linkedin: Optional[str] = None
    whatsapp: Optional[str] = None


class LeadItem(BaseModel):
    """Final unified lead item structure."""
    place_id: str = Field(description="Unique Google Maps Place ID")
    name: str = Field(description="Business Name")
    category: Optional[str] = Field(default=None, description="Primary business category")
    phone: Optional[str] = Field(default=None, description="Clean or formatted phone number")
    website_status: Literal["No Website", "Social Link Only", "Has Own Website"] = Field(
        description="Classified website status"
    )
    website_url: Optional[str] = Field(default=None, description="Website URL if real own website")
    social_links: SocialLinks = Field(default_factory=SocialLinks)
    emails: List[str] = Field(default_factory=list, description="Extracted contact email addresses")
    cms_tech: Optional[str] = Field(default=None, description="Detected CMS (WordPress, Shopify, Wix)")
    rating: Optional[float] = Field(default=None, description="Google Maps star rating")
    reviews_count: int = Field(default=0, description="Total number of reviews")
    price_range: Optional[str] = Field(default=None, description="Price tier (e.g. '৳200–400')")
    is_unclaimed_business: bool = Field(default=False, description="True if business is unverified/unclaimed")
    neighborhood: Optional[str] = Field(default=None, description="Neighborhood name")
    address: Optional[str] = Field(default=None, description="Full street address")
    lat: Optional[float] = Field(default=None, description="Latitude")
    lon: Optional[float] = Field(default=None, description="Longitude")
    order_link: Optional[str] = Field(default=None, description="Online ordering or reservation link")
    google_maps_url: Optional[str] = Field(default=None, description="Direct Google Maps URL")
    source_query: Optional[str] = Field(default=None, description="Search query that found this lead")
